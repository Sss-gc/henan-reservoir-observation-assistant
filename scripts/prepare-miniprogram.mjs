import fs from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const root = fileURLToPath(new URL('../', import.meta.url))
const mini = path.join(root, 'miniprogram')
function write(relative, contents) {
  const destination = path.join(mini, relative)
  fs.mkdirSync(path.dirname(destination), { recursive: true })
  fs.writeFileSync(destination, contents)
}
for (const name of ['recommendation', 'satellite']) {
  const source = fs.readFileSync(path.join(root, `src/services/${name}.ts`), 'utf8')
  const compiled = ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2018, module: ts.ModuleKind.CommonJS }, fileName: `${name}.ts`,
  }).outputText
  write(`utils/${name}.js`, `// Generated from src/services/${name}.ts.\n${compiled}`)
}
const collection = JSON.parse(fs.readFileSync(path.join(root, 'public/data/reservoirs.geojson'), 'utf8'))
const scopes = JSON.parse(fs.readFileSync(path.join(root, 'public/data/reservoir-sampling-scopes.geojson'), 'utf8'))
const require = createRequire(path.join(mini, 'package.json'))
const referenceLayouts = require('./data/sampling-reference.js')
fs.writeFileSync(
  path.join(root, 'public/data/sampling-reference.json'),
  `${JSON.stringify(referenceLayouts)}\n`,
)
const scopesById = Object.fromEntries(scopes.features.map((feature) => [feature.properties.id, feature]))
const roundRing = (ring) => ring.map(([lon, lat]) => [Number(lon.toFixed(6)), Number(lat.toFixed(6))])
const polygonsFor = (geometry) => (geometry.type === 'MultiPolygon' ? geometry.coordinates : [geometry.coordinates])
const reservoirs = collection.features.map(({ properties: p }) => {
  const scope = scopesById[p.id]
  if (!scope) throw new Error(`${p.id} 缺少河南库区采样范围`)
  const polygons = polygonsFor(scope.geometry).map((polygon) => polygon.map(roundRing))
  const scoped = scope.properties
  return {
    id: p.id, code: p.code, name_cn: p.name_cn,
    city: p.city.replace(/（跨湖北省十堰市）/g, ''),
    lon: scoped.lon, lat: scoped.lat,
    area_km2: scoped.sampling_area_km2,
    full_area_km2: scoped.full_area_km2,
    scope_retained_pct: scoped.retained_pct,
    sampling_scope: scoped.scope,
    shore_candidate_note: scoped.shore_candidate_note,
    shore_candidates: scoped.shore_candidates,
    polygons,
    rings: polygons.flat(),
  }
})
write('data/reservoirs.js', `// Generated by pnpm miniprogram:prepare. Do not edit.\nmodule.exports = ${JSON.stringify(reservoirs)}\n`)
console.log(`小程序共享规则与${reservoirs.length}座水库已生成。天气、轨道和Word通过专属私人静态服务读取。`)
