import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const root = fileURLToPath(new URL('../', import.meta.url))
const mini = path.join(root, 'miniprogram')
function write(relative, contents) {
  const destination = path.join(mini, relative)
  fs.mkdirSync(path.dirname(destination), { recursive: true })
  fs.writeFileSync(destination, contents)
}
for (const name of ['recommendation', 'satellite']) {
  const source = fs.readFileSync(path.join(root, `src/services/${name}.ts`), 'utf8')
  const compiled = ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2018, module: ts.ModuleKind.CommonJS }, fileName: `${name}.ts`,
  }).outputText
  write(`utils/${name}.js`, `// Generated from src/services/${name}.ts.\n${compiled}`)
}
const collection = JSON.parse(fs.readFileSync(path.join(root, 'public/data/reservoirs.geojson'), 'utf8'))
const reservoirs = collection.features.map(({ properties: p, geometry }) => ({
  id: p.id, code: p.code, name_cn: p.name_cn, city: p.city, lon: p.lon, lat: p.lat, area_km2: p.area_km2,
  rings: (geometry.type === 'MultiPolygon' ? geometry.coordinates.flat() : geometry.coordinates)
    .map((ring) => ring.map(([lon, lat]) => [Number(lon.toFixed(6)), Number(lat.toFixed(6))])),
}))
write('data/reservoirs.js', `// Generated by pnpm miniprogram:prepare. Do not edit.\nmodule.exports = ${JSON.stringify(reservoirs)}\n`)
console.log(`小程序共享规则与${reservoirs.length}座水库已生成。天气与轨道仅通过网站接口读取，不打包示例或旧轨道。`)
