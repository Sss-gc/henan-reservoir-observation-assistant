// Historical water-sampling layouts used as the default plans for reservoirs with source records.
// Coordinates remain WGS84 longitude/latitude for KML export; map display converts copies to GCJ-02.

function numberedReference(basis, year, prefix, coordinates, start = 1, padding = 2) {
  return {
    basis,
    year,
    points: coordinates.map(([longitude, latitude], index) => ({
      name: `${prefix}${String(index + start).padStart(padding, '0')}`,
      longitude,
      latitude,
    })),
  }
}

